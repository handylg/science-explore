  // 获取某周的特色内容
  getFeaturedContent(weekNum) {
    if (!weekNum) weekNum = this.getCurrentWeek();
    const featured = {
      articles: this.articles.filter(a => a.featuredWeeks.includes(weekNum)),
 videos: this.videos.filter(v => v.featuredWeeks.includes(weekNum)),
      scientists: this.scientists.filter(s => s.featuredWeeks.includes(weekNum))
    };
    // 如果本周没有匹配的内容，使用取模方式
    if (featured.articles.length === 0) {
      featured.articles = [this.articles[weekNum % this.articles.length]];
    }
    if (featured.videos.length === 0) {
      featured.videos = [this.videos[weekNum % this.videos.length]];
    }
    if (featured.scientists.length === 0) {
      featured.scientists = [this.scientists[weekNum % this.scientists.length]];
    }
    return featured;
  },

  // 获取趣味知识（每天不同）
  getDailyFacts(count = 3) {
    const today = Math.floor(Date.now() / (24 * 60 * 60 * 1000));
    const facts = [];
    for (let i = 0; i < count; i++) {
      facts.push(this.funFacts[(today + i) % this.funFacts.length]);
    }
    return facts;
  },

  // 获取随机问答题
  getQuizQuestions(count = 5) {
    const shuffled = [...this.quizQuestions].sort(() => Math.random() - 0.5);
    return shuffled.slice(0, count);
  }
